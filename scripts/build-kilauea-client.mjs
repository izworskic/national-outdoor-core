#!/usr/bin/env node
// Bundles the Kilauea engine and its episode record into one classic script the page loads, so the
// page can read USGS and Open-Meteo straight from the visitor's browser (no server function).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const strip = (src) => src.replace(/^import .*$/gm, '').replace(/^export (const|function|async function) /gm, '$1 ');
export function bundle() {
  const hist = strip(fs.readFileSync(path.join(root, 'lib/kilauea-history.mjs'), 'utf8'));
  const eng = strip(fs.readFileSync(path.join(root, 'lib/kilauea-episode-watch.mjs'), 'utf8'));
  return `// GENERATED by scripts/build-kilauea-client.mjs from lib/kilauea-history.mjs and lib/kilauea-episode-watch.mjs. Do not edit.\n(() => {\n${hist}\n${eng}\nwindow.KilaueaEngine = { buildEpisodeWatch };\n})();\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'public/assets/kilauea-engine.js'), bundle());
  console.log('Built kilauea-engine.js');
}
